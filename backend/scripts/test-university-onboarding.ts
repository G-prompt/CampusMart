import { normalizeSignupPhone } from "../src/lib/phone";
import { normalizeMatricNumber, validateMatricNumber, validAcceptedMatricFormats } from "../src/lib/studentVerification";
import { parseUniversityRosterCsv } from "../src/lib/universityRoster";
let passed=0,failed=0;
function check(ok:boolean,label:string){if(ok){passed++;console.log(`PASS ${passed+failed}: ${label}`);}else{failed++;console.error(`FAIL ${passed+failed}: ${label}`);}}
const sample=normalizeSignupPhone("0909 123 4567");
check(sample==="+2349091234567", "11 digit national Nigeria normalized");
check(normalizeSignupPhone("+234 909 123 4567")===sample, "+234 international normalized");
check(normalizeSignupPhone("+234 0909 123 4567")===sample, "+234 with accidental trunk zero normalized once");
check(normalizeSignupPhone("009091234567")===null, "duplicate leading zero rejected");
check(normalizeSignupPhone("0909123456")===null, "short phone rejected");
check(normalizeSignupPhone("090912345678")===null, "long phone rejected");
const rules=JSON.stringify([{label:"Regular",pattern:String.raw`DE\.\d{4}/\d{4}`},{label:"Transfer",pattern:String.raw`TR\.\d{4}/\d{4}`}]);
check(validAcceptedMatricFormats(rules),"two valid matric categories");
const uni={name:"Demo university",shortName:"DU",matricValidationEnabled:true,matricPattern:rules,matricFormatHint:"Regular or Transfer"};
check(validateMatricNumber("de.2022/7408",uni).valid,"regular matric accepted");
check(validateMatricNumber("TR.2022/7408",uni).valid,"transfer matric accepted");
check(!validateMatricNumber("TX.2022/7408",uni).valid,"other format rejected");
check(normalizeMatricNumber("de. 2022 /7408")==="DE.2022/7408","matric harmless spacing normalized");
const flexible=parseUniversityRosterCsv("matric_no,first_name,middle_name,last_name,faculty\nDE.2022/7408,Amara,Obi,Okoro,Science",{flexibleHeaders:true,currentStudentsOnly:true});
check(flexible.valid && flexible.acceptedRecordCount===1 && flexible.activeRecordCount===1,"split names and extra fields accepted with attestation");
check(flexible.records[0]?.fullName==="Amara Obi Okoro","split name assembled safely");
const noDeclaration=parseUniversityRosterCsv("matric_no,first_name,last_name,faculty\nDE.2022/7408,Amara,Okoro,Science",{flexibleHeaders:true});
check(!noDeclaration.valid && noDeclaration.fileErrors.some(e=>e.code==="MISSING_REQUIRED_HEADER"),"no-status roster requires declaration");
const withdrawn=parseUniversityRosterCsv("matric_no,first_name,last_name,status,department\nDE.2022/7408,Amara,Okoro,withdrawn,Science",{flexibleHeaders:true,currentStudentsOnly:true});
check(withdrawn.valid && withdrawn.inactiveRecordCount===1,"explicit withdrawal wins over attestation");
const badBlank=parseUniversityRosterCsv("matric_no,first_name,last_name,status\nDE.2022/7408,Amara,Okoro,",{flexibleHeaders:true,currentStudentsOnly:true});
check(!badBlank.valid,"blank explicit status cannot be assumed active");
check(passed+failed===16, "All intended checks ran");
console.log(`University onboarding tests: ${passed} passed / ${failed} failed`);
if(failed)process.exitCode=1;
